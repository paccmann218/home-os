/**
 * Ablation: run the SAME two-person scenario against HomeOS with FalkorDB (graph on) and with
 * FalkorDB removed (HOMEOS_GRAPH=off -> fixed rules, no memory). Writes docs/results/ablation.{json,md}.
 *
 *   npx tsx scripts/ablation.ts
 *
 * Scenario: alice says she's sick -> bob finishes a workout -> bob asks why -> alice asks what helps.
 */
import { spawn, type ChildProcess } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { REPO_ROOT } from "../src/config.js";

const TSX = path.join(REPO_ROOT, "backend", "node_modules", "tsx", "dist", "cli.mjs");
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function start(port: number, env: Record<string, string>): ChildProcess {
  return spawn(process.execPath, [TSX, "src/index.ts", "--reset"], {
    cwd: path.join(REPO_ROOT, "backend"),
    env: { ...process.env, PORT: String(port), HOMEOS_HOME: "ablation", HOMEOS_PEOPLE: "alice,bob", ESP32_HOST: "", HOMEOS_RECORD: "off", ...env },
    stdio: "ignore",
  });
}

async function waitUp(port: number) {
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch(`http://127.0.0.1:${port}/api/ping`)).ok) return;
    } catch {
      /* not yet */
    }
    await sleep(500);
  }
  throw new Error(`server on ${port} did not start`);
}

const post = async (port: number, p: string, body: unknown) =>
  (await fetch(`http://127.0.0.1:${port}${p}`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) })).json();
const state = async (port: number) => (await fetch(`http://127.0.0.1:${port}/api/state`)).json();

async function lastSay(port: number, person: string, after: number): Promise<string> {
  for (let i = 0; i < 40; i++) {
    const s = await state(port);
    const said = (s.feed as any[]).filter((e) => e.kind === "say" && e.person === person && e.at >= after).pop();
    if (said) return said.text;
    await sleep(500);
  }
  return "(nothing)";
}

async function ac(port: number) {
  const s = await state(port);
  const d = (s.devices as any[]).find((x) => x.id === "ac");
  return d?.state?.power === "on" ? `${d.state.setpoint} °C` : "off";
}

async function scenario(port: number) {
  const out: Record<string, string> = {};
  let t = Date.now();
  await post(port, "/api/chip/alice", { chip: "sick" });
  out.alice_hears = await lastSay(port, "alice", t);
  out.ac_after_alice = await ac(port);
  t = Date.now();
  await post(port, "/api/chip/bob", { chip: "workout" });
  out.bob_hears = await lastSay(port, "bob", t);
  out.ac_after_bob = await ac(port);
  out.bob_asks_why = (await post(port, "/api/ask/bob", { text: "Why is the AC set like this and not colder?", speak: false })).reply;
  out.alice_asks_what_helps = (await post(port, "/api/ask/alice", { text: "What helps me when I'm sick?", speak: false })).reply;
  return out;
}

const on = start(3003, { HOMEOS_GRAPH: "on", HOMEOS_EVAL_WINDOW_SEC: "600" });
const off = start(3004, { HOMEOS_GRAPH: "off" });
try {
  await Promise.all([waitUp(3003), waitUp(3004)]);
  const withGraph = await scenario(3003);
  const withoutGraph = await scenario(3004);
  const result = { at: new Date().toISOString(), withGraph, withoutGraph };
  const dir = path.join(REPO_ROOT, "docs", "results");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "ablation.json"), JSON.stringify(result, null, 2));
  const rows = Object.keys(withGraph)
    .map((k) => `| ${k.replace(/_/g, " ")} | ${withGraph[k].replace(/\|/g, "/")} | ${withoutGraph[k]?.replace(/\|/g, "/")} |`)
    .join("\n");
  const md = `# Ablation: HomeOS with and without FalkorDB\n\nGenerated by \`backend/scripts/ablation.ts\` on ${result.at}. Same scenario, same code; the only difference is \`HOMEOS_GRAPH\`.\n\n| Step | FalkorDB on | FalkorDB off (fixed rules) |\n|---|---|---|\n${rows}\n`;
  fs.writeFileSync(path.join(dir, "ablation.md"), md);
  console.log(md);
} finally {
  on.kill();
  off.kill();
}
